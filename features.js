    article.appendChild(heading);

    const details = document.createElement("p");
    const flow = featureText("flowValues")[entry.flow];
    const mood = featureText("moodValues")[entry.mood];
    const symptoms = entry.symptoms.map(value => featureText("symptomValues")[value]).join(", ");
    const detailParts = [
      `${featureText("flowLabel")}: ${flow}`,
      `${featureText("moodLabel")}: ${mood}`
    ];
