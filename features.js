async function submitAccountAuth(mode) {
  if (!navigator.onLine) {
    setFeatureStatus("accountStatus", featureText("accountNetworkError"), true);
    return;
  }
  const emailInput = $("accountEmail");
  const passwordInput = $("accountPassword");
  const email = emailInput.value.trim().toLowerCase();
  const password = passwordInput.value;
  if (!emailInput.validity.valid || !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) {
    setFeatureStatus("accountStatus", featureText("accountEmailInvalid"), true);
    emailInput.focus();
    return;
  }
  if (password.length < 12 || new TextEncoder().encode(password).length > 72) {
    setFeatureStatus("accountStatus", featureText("accountPasswordInvalid"), true);
    passwordInput.focus();
    return;
  }
  setAccountBusy(true);
  try {
    const result = await apiRequest(`/api/auth/${mode}`, {
      method: "POST",
      body: JSON.stringify({ email, password })
    });
    accountUser = result.user;
    passwordInput.value = "";
    renderAccountState();
    setFeatureStatus(
      "accountStatus",
      featureText(mode === "register" ? "accountRegisterSuccess" : "accountLoginSuccess")
    );
  } catch (error) {
    console.error(`SakhiCare account ${mode} request failed:`, error.message);
    setFeatureStatus("accountStatus", accountErrorMessage(error, mode), true);
  } finally {
    setAccountBusy(false);
  }
}

