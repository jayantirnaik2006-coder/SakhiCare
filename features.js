function reportStorageError(error, statusId, message) {
  console.error("SakhiCare browser storage operation failed:", error);
  setFeatureStatus(statusId, message, true);
}

function readStoredValue(key, fallback, statusId = "privacyStatus") {
  try {
    const value = localStorage.getItem(key);
    return value === null ? fallback : JSON.parse(value);
  } catch (error) {
    reportStorageError(error, statusId, featureText("storageReadError"));
    return fallback;
  }
}

function writeStoredValue(key, value, statusId, message) {
  try {
    localStorage.setItem(key, JSON.stringify(value));
    return true;
  } catch (error) {
    reportStorageError(error, statusId, message);
    return false;
  }
}

function localDateString(date = new Date()) {
  const year = date.getFullYear();
  const month = String(date.getMonth() + 1).padStart(2, "0");
  const day = String(date.getDate()).padStart(2, "0");
  return `${year}-${month}-${day}`;
}

function parseLocalDate(value) {
  if (typeof value !== "string" || !/^\d{4}-\d{2}-\d{2}$/.test(value)) return null;
  const [year, month, day] = value.split("-").map(Number);
  const date = new Date(year, month - 1, day);
  return date.getFullYear() === year && date.getMonth() === month - 1 && date.getDate() === day
    ? date
    : null;
}

function formatDate(value) {
  const date = parseLocalDate(value);
  return date ? new Intl.DateTimeFormat(featureLanguage(), { dateStyle: "medium" }).format(date) : value;
}

function validJournalEntry(entry) {
  return entry && typeof entry === "object" &&
    typeof entry.id === "string" &&
    parseLocalDate(entry.date) &&
    flowValues.includes(entry.flow) &&
    moodValues.includes(entry.mood) &&
    Array.isArray(entry.symptoms) &&
    entry.symptoms.every(symptom => symptomValues.includes(symptom)) &&
    typeof entry.note === "string";
}

function loadJournal() {
  const stored = readStoredValue(journalStorageKey, []);
  if (!Array.isArray(stored)) {
    setFeatureStatus("privacyStatus", featureText("storageReadError"), true);
    return [];
  }
  if (!stored.every(validJournalEntry)) {
    setFeatureStatus("privacyStatus", featureText("storageReadError"), true);
    return stored.filter(validJournalEntry);
  }
  return stored;
}

function loadReminderSettings() {
  const stored = readStoredValue(reminderStorageKey, { enabled: false, lead: 0, lastNotified: "" });
  if (!stored || typeof stored !== "object" || ![0, 1, 3, 7].includes(Number(stored.lead))) {
    return { enabled: false, lead: 0, lastNotified: "" };
  }
  return {
    enabled: stored.enabled === true,
    lead: Number(stored.lead),
    lastNotified: typeof stored.lastNotified === "string" ? stored.lastNotified : ""
  };
}

