async function apiRequest(path, options = {}) {
  let response;
  try {
    response = await fetch(path, {
      credentials: "same-origin",
      ...options,
      headers: {
        ...(options.body ? { "Content-Type": "application/json" } : {}),
        ...options.headers
      }
    });
  } catch (error) {
    throw new Error("NETWORK");
  }
  if (response.status === 204) return {};
  let payload = {};
  try {
    payload = await response.json();
  } catch (error) {
    if (response.ok) throw new Error("SERVER");
  }
  if (!response.ok) {
    throw new Error(payload.error && payload.error.code ? payload.error.code : "SERVER");
  }
  return payload;
}

function accountErrorMessage(error, operation) {
  switch (error.message) {
    case "NETWORK":
      return featureText("accountNetworkError");
    case "AUTH_REQUIRED":
      accountUser = null;
      renderAccountState();
      return featureText("accountSessionExpired");
    case "INVALID_CREDENTIALS":
      return featureText("accountLoginError");
    case "EMAIL_IN_USE":
      return featureText("accountEmailInUse");
    case "RATE_LIMITED":
      return featureText("accountRateLimited");
    case "VALIDATION_ERROR":
      return operation === "register"
        ? featureText("accountRegisterError")
        : featureText("accountDataError");
    default:
      return featureText("accountServerError");
  }
}

