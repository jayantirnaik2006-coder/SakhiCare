function readLocalBundle() {
  return {
    cycle: JSON.parse(localStorage.getItem(cycleStorageKey) || "null"),
    journal: JSON.parse(localStorage.getItem(journalStorageKey) || "[]"),
    reminder: JSON.parse(localStorage.getItem(reminderStorageKey) || '{"enabled":false,"lead":0,"lastNotified":""}')
  };
}

function validateClientBundle(data) {
  if (!data || typeof data !== "object" ||
      (data.cycle !== null && (!data.cycle || !parseLocalDate(data.cycle.date) ||
        !Number.isInteger(Number(data.cycle.length)) || Number(data.cycle.length) < 15 || Number(data.cycle.length) > 60)) ||
      !Array.isArray(data.journal) || !data.journal.every(validJournalEntry) ||
      !data.reminder || typeof data.reminder !== "object" ||
      typeof data.reminder.enabled !== "boolean" ||
      ![0, 1, 3, 7].includes(Number(data.reminder.lead))) {
    throw new Error("INVALID_DATA");
  }
  return {
    cycle: data.cycle ? { date: data.cycle.date, length: Number(data.cycle.length) } : null,
    journal: data.journal,
    reminder: {
      enabled: data.reminder.enabled,
      lead: Number(data.reminder.lead),
      lastNotified: typeof data.reminder.lastNotified === "string" ? data.reminder.lastNotified : ""
    }
  };
}

function replaceLocalBundle(data) {
  const bundle = validateClientBundle(data);
  const values = [
    [cycleStorageKey, bundle.cycle],
    [journalStorageKey, bundle.journal],
    [reminderStorageKey, bundle.reminder]
  ];
  const previous = values.map(([key]) => [key, localStorage.getItem(key)]);
  try {
    values.forEach(([key, value]) => localStorage.setItem(key, JSON.stringify(value)));
  } catch (error) {
    previous.forEach(([key, value]) => {
      try {
        if (value === null) localStorage.removeItem(key);
        else localStorage.setItem(key, value);
      } catch (rollbackError) {
        console.error("SakhiCare local data rollback failed:", rollbackError);
      }
    });
    throw error;
  }
  journalEntries = bundle.journal;
  selectedEntryIds.clear();
  reminderSettings = bundle.reminder;
  $("periodDate").value = bundle.cycle ? bundle.cycle.date : "";
  $("cycleLength").value = bundle.cycle ? String(bundle.cycle.length) : "28";
  $("journalForm").reset();
  $("journalDate").value = localDateString();
  $("cycleResult").replaceChildren();
  $("cycleResult").classList.add("hidden");
  renderCalendar();
  renderJournalEntries();
  renderPersonalDashboard();
  updateReminderStatus();
}

